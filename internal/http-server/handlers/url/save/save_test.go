func TestNew_AliasAlreadyExists_AutoGenerated_Retries(t *testing.T) {
	callCount := 0
	mockURLSaver := &MockURLSaverWithCounter{
		saveFunc: func(ctx context.Context, urlToSave string, alias string) (int, error) {
			callCount++
			if callCount <= 2 {
				return 0, storage.ErrAliasExists
			}
			return 123, nil
		},
	}
	logger := newTestLogger()
	handler := New(logger, mockURLSaver)

	body := []byte(`{"url":"https://example.com"}`)
	req := createTestRequest(body)
	w := httptest.NewRecorder()

	handler(w, req)

	assert.Equal(t, http.StatusOK, w.Code)
	assert.Contains(t, w.Body.String(), "OK")
	assert.Equal(t, 3, callCount, "SaveURL should be called 3 times (2 failures + 1 success)")
}

