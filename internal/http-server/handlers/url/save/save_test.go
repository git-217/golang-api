type MockURLSaver struct {
	id  int
	err error
}

func (m *MockURLSaver) SaveURL(ctx context.Context, urlToSave string, alias string) (int, error) {
	return m.id, m.err
}

type MockURLSaverWithCounter struct {
	saveFunc func(ctx context.Context, urlToSave string, alias string) (int, error)
}

func (m *MockURLSaverWithCounter) SaveURL(ctx context.Context, urlToSave string, alias string) (int, error) {
	return m.saveFunc(ctx, urlToSave, alias)
}

func createTestRequest(body []byte) *http.Request {
	req := httptest.NewRequest(http.MethodPost, "/url", bytes.NewBuffer(body))
	req = req.WithContext(context.WithValue(req.Context(), chi.RouteCtxKey, chi.NewRouteContext()))
	return req
}

func newTestLogger() *slog.Logger {
	return slog.New(slog.NewJSONHandler(io.Discard, nil))
}

func TestNew(t *testing.T) {
	tests := []struct {
		name           string
		body           string
		mockID         int
		mockErr        error
		expectedStatus int
		expectedAlias  string
		expectedError  string
	}{
		{
			name:           "success with custom alias",
			body:           `{"url":"https://example.com","alias":"myalias"}`,
			mockID:         1,
			mockErr:        nil,
			expectedStatus: http.StatusOK,
			expectedAlias:  "myalias",
		},
		{
			name:           "success with auto-generated alias",
			body:           `{"url":"https://example.com"}`,
			mockID:         1,
			mockErr:        nil,
			expectedStatus: http.StatusOK,
			expectedAlias:  "",
		},
		{
			name:           "URL without https protocol",
			body:           `{"url":"http://example.com","alias":"myalias"}`,
			mockID:         0,
			mockErr:        nil,
			expectedStatus: http.StatusOK,
			expectedError:  "URL must starts with 'https://'",
		},
		{
			name:           "invalid URL format",
			body:           `{"url":"not-a-url","alias":"myalias"}`,
			mockID:         0,
			mockErr:        nil,
			expectedStatus: http.StatusOK,
			expectedError:  "URL must starts with 'https://'",
		},
		{
			name:           "empty URL (required field)",
			body:           `{"url":"","alias":"myalias"}`,
			mockID:         0,
			mockErr:        nil,
			expectedStatus: http.StatusOK,
			expectedError:  "URL must starts with 'https://'",
		},
		{
			name:           "alias already exists (user-provided)",
			body:           `{"url":"https://example.com","alias":"existing"}`,
			mockID:         0,
			mockErr:        storage.ErrAliasExists,
			expectedStatus: http.StatusOK,
			expectedError:  "alias already exists",
		},
		{
			name:           "storage error",
			body:           `{"url":"https://example.com","alias":"myalias"}`,
			mockID:         0,
			mockErr:        errors.New("database error"),
			expectedStatus: http.StatusOK,
			expectedError:  "failed to save URL",
		},
		{
			name:           "max attempts reached for unique alias",
			body:           `{"url":"https://example.com"}`,
			mockID:         0,
			mockErr:        storage.ErrAliasExists,
			expectedStatus: http.StatusOK,
			expectedError:  "failed to generate unique alias",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			mockSaver := &MockURLSaver{
				id:  tt.mockID,
				err: tt.mockErr,
			}
			logger := newTestLogger()
			handler := New(logger, mockSaver)

			req := createTestRequest([]byte(tt.body))
			w := httptest.NewRecorder()

			handler(w, req)

			if tt.expectedError != "" {
				assert.Equal(t, http.StatusOK, w.Code)
				assert.Contains(t, w.Body.String(), tt.expectedError)
			} else {
				assert.Equal(t, tt.expectedStatus, w.Code)
				if tt.expectedAlias != "" {
					assert.Contains(t, w.Body.String(), tt.expectedAlias)
				}
				assert.Contains(t, w.Body.String(), "OK")
			}
		})
	}
}

func TestNew_SuccessWithCustomAlias(t *testing.T) {
	mockSaver := &MockURLSaver{
		id:  123,
		err: nil,
	}
	logger := newTestLogger()
	handler := New(logger, mockSaver)

	body := []byte(`{"url":"https://example.com","alias":"myalias"}`)
	req := createTestRequest(body)
	w := httptest.NewRecorder()

	handler(w, req)

	assert.Equal(t, http.StatusOK, w.Code)
	assert.Contains(t, w.Body.String(), `"alias":"myalias"`)
	assert.Contains(t, w.Body.String(), `"status":"OK"`)
}

